import path from 'path';
import { extract } from './extractor.js';
import { optimizeExtractedCss } from './optimizer.js';
import { htmlStrategy } from './formats/html.js';
import { readGeneratedFiles, reconcileGeneratedFiles } from './output-cleanup.js';
import { sanitizeFileName } from './constants.js';
import { writeExportReport } from './export-report.js';
import { loadUncagePlugins, runAssembleHooks, runHTMLRewriteHooks } from './plugins.js';
import type { ExtractorOptions, ProgressHandler, ProgressEvent } from './types.js';

export interface CloneResult {
  pages: Record<string, string>;
  outputDir: string;
  originalHead: string;
  runtimeScripts: string[];
}

// Shared pipeline: extract → optimize → compile → assemble, always Static HTML.
// Both the CLI and the web UI call this so their behavior stays identical.
export async function cloneToStaticHtml(
  url: string,
  outputName: string,
  options: ExtractorOptions & { purge?: boolean; keepAnalytics?: boolean } = {},
  onProgress?: ProgressHandler
): Promise<CloneResult> {
  const emit = (kind: ProgressEvent['kind'], message: string): void => {
    try { onProgress?.({ kind, message }); } catch { /* listener must never break the run */ }
  };

  const plugins = options.plugins ?? await loadUncagePlugins();
  if (plugins.length > 0) {
    const message = `Loaded ${plugins.length} plugin(s) from uncage.config.ts`;
    console.log(`  [Plugins] ${message}`);
    emit('info', message);
  }

  const extractorOptions: ExtractorOptions = { ...options, plugins };
  if (onProgress) extractorOptions.onProgress = onProgress;

  const previous = await readGeneratedFiles(outputPathFor(outputName));

  // Step 1: Extract (stealth crawler, asset harvest, HTML capture)
  emit('phase', 'Starting extraction');
  const { pages, outputDir, originalHead, runtimeScripts } = await extract(url, outputName, extractorOptions);

  for (const [route, html] of Object.entries(pages)) {
    const pageUrl = new URL(route === '/index' ? '/' : route, url).href;
    pages[route] = await runHTMLRewriteHooks(plugins, { url: pageUrl, route, html }, (message) => emit('warn', message));
  }

  // Step 1.5: Minify CSS; remove selectors only when explicitly requested.
  emit('phase', options.purge === true ? 'Purging and minifying CSS' : 'Minifying CSS');
  await optimizeExtractedCss(outputDir, pages, options.purge === true);

  // Step 2: Compile HTML pages into static HTML/CSS/JS
  emit('phase', 'Compiling static HTML');
  await htmlStrategy.compile(outputDir, pages, runtimeScripts, {
    keepAnalytics: options.keepAnalytics,
    onProgress,
  });

  // Step 3: Assemble (finalize static project structure)
  emit('phase', 'Assembling static project');
  await htmlStrategy.assemble(outputDir, url, originalHead, Object.keys(pages), runtimeScripts, {
    keepAnalytics: options.keepAnalytics,
    onProgress,
  });
  await runAssembleHooks(plugins, { outputDir, sourceUrl: url, routes: Object.keys(pages) }, (message) => emit('warn', message));

  // Move files generated by an earlier run but absent from this export into
  // output/.uncage-archive, preserving any edits made to those files.
  await reconcileGeneratedFiles(outputDir, previous, Object.keys(pages));

  try {
    const report = await writeExportReport(outputDir, url, Object.keys(pages));
    const { pages: pageCount, mappedAssets, missingPages, missingAssets, brokenLocalReferences, externalResources } = report.summary;
    const issues = missingPages + missingAssets + brokenLocalReferences;
    const message = `Export quality: ${pageCount} page(s), ${mappedAssets} mapped asset(s), ${issues} missing local file/reference(s), ${externalResources} external resource(s). See export-report.json.`;
    console.log(`  [Report] ${message}`);
    emit(issues > 0 ? 'warn' : 'info', message);
  } catch (error) {
    const message = `Could not write export quality report: ${error instanceof Error ? error.message : String(error)}`;
    console.log(`  ⚠️ ${message}`);
    emit('warn', message);
  }

  emit('info', `Exported ${Object.keys(pages).length} page(s)`);
  return { pages, outputDir, originalHead, runtimeScripts };
}

export function outputPathFor(outputName: string): string {
  return path.join(process.cwd(), 'output', sanitizeFileName(outputName) || 'extracted-site');
}
